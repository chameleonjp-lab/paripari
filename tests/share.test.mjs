import {setLanguage} from '../src/js/i18n.js';
setLanguage('ja',{persist:false});
import assert from 'node:assert/strict';
import { currentGameUrl, shareOrCopy } from '../src/js/platform.js';
let opened = null;
globalThis.window = { location: { href: 'http://localhost:8080/?debug=1#x' }, open(url) { opened = url; return { opener: {} }; } };
assert.equal(currentGameUrl(), 'https://chameleonjp-lab.github.io/paripari/');
const statusElement = { textContent: '' };
const textElement = { value: '', hidden: true, focus() {}, select() {} };
const text = 'パリパリ\n今回123点 & # / ?\n' + currentGameUrl();
await shareOrCopy({text, statusElement, textElement});
assert.equal(new URL(opened).origin, 'https://x.com');
assert.equal(new URL(opened).searchParams.get('text'), text);
assert.doesNotMatch(statusElement.textContent, /投稿完了|共有しました/);
window.open = () => null;
Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { clipboard: { async writeText(value) { assert.equal(value, text); } } } });
await shareOrCopy({text, statusElement, textElement});
assert.match(statusElement.textContent, /コピーしました/);
navigator.clipboard.writeText = async () => { throw new Error('blocked'); };
await shareOrCopy({text, statusElement, textElement});
assert.equal(textElement.value, text);
assert.equal(textElement.hidden, false);
console.log('X sharing and copy fallbacks verified');
